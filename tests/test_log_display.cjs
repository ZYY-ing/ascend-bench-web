const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/../runner-src/scripts/runner-client.js','utf8');
const body=source.match(/function executionLogText\(log\)\{[\s\S]*?\n\}/)[0];
const format=vm.runInNewContext(body+';executionLogText');
const native='\n\n\x1b[32mINFO\x1b[0m start\n\n\nWarmup: 100%|██| 1/1\r\n\nPOST=0 (0.0/s)  RECV=0 (0.0/s)   \x1b[A\n\nPOST=0 (0.0/s)  RECV=0 (0.0/s)   \x1b[A\n\nProgress: 100%|██| 2/2\r\n\nPerformance results\n\n';
const result=format(native);
assert(!result.includes('\x1b'));assert(!result.includes('\n\n\n'));
assert.equal(result.match(/POST=0/g).length,1);
assert(result.indexOf('Warmup:')<result.indexOf('Progress:'));assert(result.indexOf('Progress:')<result.indexOf('Performance results'));
assert.equal(format('HTTP 400\nHTTP 400'),'HTTP 400\nHTTP 400');
assert.equal(format('[INFO] Warmup finished Total Count: 1 Success Count: 1 Failed Count: 0\nResults\nWarmup finished Total Count: 1 Success Count: 1 Failed Count: 0'),'[INFO] Warmup finished Total Count: 1 Success Count: 1 Failed Count: 0\nResults');
assert.equal(format('before\n[Runner terminal frame begin]\nold native table\n[Runner terminal frame end]\nafter'),'before\nold native table\nafter');
const tail=source.match(/function _tailLog\(r\)\{[^\n]+/)[0];
const exportLog=vm.runInNewContext(body+';'+tail+';_tailLog');
assert(exportLog({status:'completed',log:native}).includes('INFO start'));
assert(source.includes('执行日志（完整）'));assert(source.includes('},5000)'));
assert(!source.includes('function showNativeTerminal'));
assert(fs.readFileSync(__dirname+'/../runner-src/website/config.js','utf8').includes("reuse:'',debug:true,max_num_workers:1"));
console.log('Unified native logs: order, ANSI removal, blank-line cleanup, progress deduplication and complete export passed.');
